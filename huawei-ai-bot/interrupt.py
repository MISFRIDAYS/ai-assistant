"""คำถามค้าง vs คำสั่งใหม่

หลายส่วนถามกลับแล้วรอคำตอบ (หมายถึงใคร/ส่งทางไหน · นัดวันไหน · เลข Job อะไร …)
ถ้าผู้ใช้เปลี่ยนใจพูดคำสั่งใหม่ทั้งประโยค ต้องทิ้งคำถามค้างแล้วทำคำสั่งใหม่ — ห้ามเอาไปเป็นคำตอบ
(v73: 'เข้าไปที่ instagram … ส่งข้อความ …' ถูกอ่านเป็น 'เลือกภรรยา (LINE)' แล้วส่งผิดแอป)
"""
import re

import chat_apps

_OPEN = re.compile(r"(?:^|\s)(?:ช่วย)?\s*(?:เข้า|เปิด|ไปที่|ไปหน้า|กลับไป)\s*(?:ไป)?\s*(?:ที่|ใน)?\s*"
                   r"(?:แชท|แชต|แอป|แอพ|ห้อง|หน้า|youtube|ยูทูบ|ยูทูป|chrome|โครม)", re.I)
_SEND = re.compile(r"(?:ส่ง|พิมพ์|ทัก|ตอบ|บอก|เขียน).{0,60}(?:ข้อความ|แชท|แชต)|(?:ข้อความ|แชท|แชต).{0,60}(?:ส่ง|พิมพ์|ว่า)")
# คำสั่งขึ้นต้นด้วยคำกริยาสั่งงาน (คำตอบ เช่น ชื่อนัด 'คุยเรื่องส่งข้อความหาลูกค้า' ไม่นับ)
_VERB = re.compile(r"^(?:โอเค|ok|เอ่อ|อ่า|แล้วก็|งั้น)?\s*(?:ช่วย|ขอ)?\s*(?:เปิด|ปิด|เข้า|ไปที่|ไปหน้า|กลับไป|ส่ง|พิมพ์|ทัก|ตอบ|บอก|"
                   r"เขียน|โทร|ตั้ง|เล่น|หา|ค้นหา|ถ่าย|อ่าน|สรุป|เพิ่ม|ลบ)", re.I)


def is_new_command(text, min_len=20):
    """ประโยคนี้เป็นคำสั่งใหม่ทั้งประโยค (ไม่ใช่คำตอบสั้น ๆ ของคำถามที่ค้าง)"""
    t = " ".join(re.sub(r"\[[^\]]*\]", " ", text or "").split())
    if len(t) <= min_len:
        return False
    if not _VERB.search(t):
        return False
    app, _ = chat_apps.find(t)
    return bool(_SEND.search(t) or _OPEN.search(t) or app)   # ส่งข้อความ / เข้าแอป-แชท / "เปิดไลน์แล้ว…"
