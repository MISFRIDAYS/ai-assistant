    for cat, items in CATEGORIES.items():
        lines.append(cat)
        lines.extend(f"• {p}" for p in items)
        lines.append("")
    lines.append("คำสั่งลัด: " + " · ".join(f"/{c}" for c, _ in COMMANDS))
    return "\n".join(lines)
