"""คำลงท้ายตามเพศของผู้ใช้/ผู้ช่วย — ตั้ง POLITE=ครับ (ค่าเริ่มต้น) แล้วข้อความที่ AI เขียนจะใช้ "ครับ" อย่างเดียว
ใช้กับข้อความที่ AI แต่ง (คำตอบ, ข้อความที่เขียนให้ส่ง, ตอบแชทแทน) — ไม่แตะข้อความที่ผู้ใช้บอกให้พิมพ์ตรงตัว
"""
import os
import re

_END = r"(?=[\s?!.,…)\]\"'”~😀-🙏🤍-🫶]|$)"


def mode():
    return os.environ.get("POLITE", "ครับ").strip() or "ครับ"


def fix(text):
    if not text or mode() != "ครับ":
        return text
    t = re.sub(r"(ครับ|ค่ะ|คะ)\s*/\s*(ครับ|ค่ะ|คะ)", "ครับ", text)       # "ครับ/ค่ะ" → "ครับ"
    t = re.sub(r"นะคะ" + _END, "นะครับ", t)
    t = re.sub(r"ค่ะ" + _END, "ครับ", t)
    t = re.sub(r"(?<=[ก-๙])คะ" + _END, "ครับ", t)                        # ไหมคะ/ไหนคะ → ครับ (ไม่แตะ "คะแนน")
    t = re.sub(r"(?<![ก-๙])คะ" + _END, "ครับ", t)
    t = re.sub(r"ดิฉัน", "ผม", t)
    return t
